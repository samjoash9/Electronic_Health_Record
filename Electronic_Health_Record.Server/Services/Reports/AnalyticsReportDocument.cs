                imageBase64: Model.ConditionsChartBase64,
                imageHeight: 155,
                clinicalSummary:
                    "Morbidity Surveillance & Chronic Disease Profile:\n" +
                    "• Clinical Distribution: Non-communicable diseases (NCDs) represent the dominant caseload. Hypertension ranks as the primary diagnosis at 45%, followed by degenerative joint disease / Arthritis (25%), Diabetes Mellitus (18%), and confirmed/suspected Oncological cases (12%).\n" +
                    "• Key Vulnerabilities: Hypertension and Diabetes jointly comprise 63% of chronic diagnoses, demanding proactive glycemic control and blood pressure monitoring protocols.\n" +
                    "• Recommendations: Elevate routine screening at Station 3 (NCD Station) and provide targeted pharmacological and nutritional intervention pathways.",
                badgeText: "CHRONIC CARE FOCUS"
            ));

            // ==========================================
            // 2. Patient Entry Trends
            // ==========================================
            col.Item().Element(c => ComposeSection(
                c,
                title: "2. Patient Entry Trends & Period Volatility",
