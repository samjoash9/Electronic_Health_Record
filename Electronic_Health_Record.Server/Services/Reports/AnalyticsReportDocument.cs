                badgeText: "PREVENTIVE HEALTH"
            ));
        });
    }

    private void ComposeSection(
        IContainer container,
        string title,
        string subtitle,
        string? imageBase64,
        float imageHeight,
        string clinicalSummary,
        string badgeText)
    {
        container.Border(1).BorderColor("#e2e8f0").Background("#ffffff").Padding(12).Column(col =>
        {
            col.Item().Row(r =>
            {
                r.RelativeItem().Column(titleCol =>
                {
                    titleCol.Item().Text(title).FontSize(11.5f).Bold().FontColor("#0f172a");
                    titleCol.Item().Text(subtitle).FontSize(8.5f).FontColor("#64748b");
                });

                r.ConstantItem(120).AlignRight().Background("#f1f5f9").PaddingVertical(3).PaddingHorizontal(6).Text(badgeText)
                    .FontSize(7).SemiBold().FontColor("#475569");
            });

            col.Item().PaddingTop(8).Row(contentRow =>
            {
                contentRow.Spacing(12);

                // Chart visual on left side
                var imageBytes = DecodeBase64(imageBase64);
                if (imageBytes != null && imageBytes.Length > 0)
                {
                    contentRow.ConstantItem(220).Height(imageHeight).Border(1).BorderColor("#f1f5f9").Background("#f8fafc")
                        .Padding(4).Image(imageBytes).FitArea();
                }
                else
                {
                    contentRow.ConstantItem(220).Height(imageHeight).Border(1).BorderColor("#f1f5f9").Background("#f8fafc")
                        .AlignCenter().AlignMiddle().Text("Visualization Graph").FontSize(9).FontColor("#94a3b8");
                }

                // Clinical summary narrative on right side
                contentRow.RelativeItem().Column(descCol =>
                {
                    descCol.Item().Text("Clinical Review & Diagnostic Insights")
                        .FontSize(9.5f).SemiBold().FontColor("#0f766e");

                    descCol.Item().PaddingTop(4).Text(clinicalSummary)
                        .FontSize(8.5f).LineHeight(1.35f).FontColor("#334155");
                });
            });
        });
    }

    private void ComposeFooter(IContainer container)
    {
        container.Column(col =>
        {
            col.Item().LineHorizontal(1).LineColor("#e2e8f0");
            col.Item().PaddingTop(6).Row(row =>
            {
                row.RelativeItem().Text(
                    "CONFIDENTIAL CLINICAL RECORD — Electronic Health Record & Wellness System (eHPR). For authorized medical staff only.")
                    .FontSize(7.5f)
                    .FontColor("#94a3b8");

                row.ConstantItem(100).AlignRight().Text(text =>
                {
                    text.Span("Page ").FontSize(8).FontColor("#64748b");
                    text.CurrentPageNumber().FontSize(8).SemiBold().FontColor("#0f172a");
                    text.Span(" of ").FontSize(8).FontColor("#64748b");
                    text.TotalPages().FontSize(8).SemiBold().FontColor("#0f172a");
                });
            });
        });
    }

    private static byte[]? DecodeBase64(string? base64)
    {
        if (string.IsNullOrWhiteSpace(base64)) return null;
        try
        {
            var clean = base64;
            var commaIndex = clean.IndexOf(',');
            if (commaIndex >= 0)
            {
                clean = clean.Substring(commaIndex + 1);
            }
            return Convert.FromBase64String(clean);
        }
        catch
        {
            return null;
        }
    }
}
