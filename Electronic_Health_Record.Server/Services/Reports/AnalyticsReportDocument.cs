using Electronic_Health_Record.Server.DTOs.Reports;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace Electronic_Health_Record.Server.Services.Reports;

public class AnalyticsReportDocument : IDocument
{
    public AnalyticsReportPdfRequest Model { get; }

    public AnalyticsReportDocument(AnalyticsReportPdfRequest model)
    {
        Model = model;
    }

    public DocumentMetadata GetMetadata() => DocumentMetadata.Default;

    public void Compose(IDocumentContainer container)
    {
        container
            .Page(page =>
            {
                page.Size(PageSizes.A4);
                page.MarginTop(24);
                page.MarginBottom(24);
                page.MarginLeft(28);
                page.MarginRight(28);
                page.DefaultTextStyle(x => x.FontSize(9.5f).FontColor("#1e293b"));

                page.Header().Element(ComposeHeader);
                page.Content().Element(ComposeContent);
                page.Footer().Element(ComposeFooter);
            });
    }

    private void ComposeHeader(IContainer container)
    {
        container.Column(col =>
        {
            col.Item().Row(row =>
            {
                row.RelativeItem().Column(titleCol =>
                {
                    titleCol.Item().Text("PROVINCIAL HEALTH OFFICE — eHPR SYSTEM")
                        .FontSize(11)
                        .SemiBold()
                        .FontColor("#0f766e");

                    titleCol.Item().Text("Clinical Analytics & Station Throughput Report")
                        .FontSize(18)
                        .Bold()
                        .FontColor("#0f172a");

                    titleCol.Item().Text("Comprehensive Population Wellness & Diagnostic Surveillance Summary")
                        .FontSize(9)
                        .FontColor("#64748b");
                });

                row.ConstantItem(150).AlignRight().Column(metaCol =>
                {
                    metaCol.Item().Text($"Date: {DateTime.Now:MMMM dd, yyyy}")
                        .FontSize(8.5f)
                        .SemiBold()
                        .FontColor("#334155");

                    metaCol.Item().Text($"Time: {DateTime.Now:hh:mm tt}")
                        .FontSize(8)
                        .FontColor("#64748b");

                    metaCol.Item().Text($"Generated by: {Model.GeneratedBy ?? "Clinical Admin"}")
                        .FontSize(8)
                        .FontColor("#64748b");
                });
            });

            // Metadata KPI Banner
            col.Item().PaddingTop(10).PaddingBottom(12).Row(kpiRow =>
            {
                kpiRow.Spacing(8);

                kpiRow.RelativeItem().Background("#f0fdfa").Border(1).BorderColor("#ccfbf1").Padding(8).Column(c =>
                {
                    c.Item().Text("TOTAL FORMS").FontSize(7.5f).SemiBold().FontColor("#0f766e");
                    c.Item().Text(Model.TotalForms.ToString("N0")).FontSize(13).Bold().FontColor("#115e59");
                });

                kpiRow.RelativeItem().Background("#eff6ff").Border(1).BorderColor("#dbeafe").Padding(8).Column(c =>
                {
                    c.Item().Text("TOTAL PATIENTS").FontSize(7.5f).SemiBold().FontColor("#2563eb");
                    c.Item().Text(Model.TotalPatients.ToString("N0")).FontSize(13).Bold().FontColor("#1e40af");
                });

                kpiRow.RelativeItem().Background("#f0fdf4").Border(1).BorderColor("#dcfce7").Padding(8).Column(c =>
                {
                    c.Item().Text("COMPLETED ASSESSMENTS").FontSize(7.5f).SemiBold().FontColor("#16a34a");
                    c.Item().Text(Model.CompletedForms.ToString("N0")).FontSize(13).Bold().FontColor("#166534");
                });

                kpiRow.RelativeItem().Background("#faf5ff").Border(1).BorderColor("#f3e8ff").Padding(8).Column(c =>
                {
                    c.Item().Text("FACILITY STATUS").FontSize(7.5f).SemiBold().FontColor("#9333ea");
                    c.Item().Text("ACTIVE ALL STATIONS").FontSize(11).Bold().FontColor("#6b21a8");
                });
            });

            col.Item().LineHorizontal(1).LineColor("#e2e8f0");
        });
    }

